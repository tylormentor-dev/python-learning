#As a developer, you're code will have to go through refactoring, which means that you rewrite or rework the code to make it easier to manage or to run more efficiently. 

#To determine how to make code faster or perform better, you must be able to measure it. 
#Code is measured by time and space. 
#Time is measured by how long it takes, and space it about how much memory it uses. 

#Constant time: This is an algorithm that will always run under the same time and space regardless of the size. 
#Linear time: This will grow depending on the size of the input. 
#Logarithmic time: Refers to the running time of the inputs against the number of operations.
#Exponential time: An algorithm that doubles with each iteration. The Fibonacci sequence is a prime example of this. 