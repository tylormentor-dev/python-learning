#Variables are used to store different types of data. 
#Variables helps you to manipulate data.
#The word 'Variable' refer to something that can be changed.
#The naming convention for variables are important because it can be challenging to remember why you used a specific variable when you have to interact with your code months after it was written.
#When working with other developers it can be difficult to know what a variable refers to unless it has a meaningful label.

#Naming conventions for variables:
#camelCase: 
