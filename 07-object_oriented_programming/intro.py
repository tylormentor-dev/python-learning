#Programming languages are build on a certain models to ensure that the code behaves predictably. 
#Python allows a object-oriented paradigm or model, which relies heavy on simplicity and usability to improve workflow.

#Programming paradigms is a strategy for reducing code complexity and determining the flow of execution.

#There are seven types of paradigms: Declarative, Procedural, Object-Oriented, Function, Logic, Event-Driven, Flow-Driven and more.
#Python is object-oriented, procedural and functional.
#A paradigm can be defined as a style of writing or program. 

#OOP's ability to translate real world problems into code is the biggest factor in it's success.
#OOP has high modularity which makes code easier to understand, reusable, layers of abstraction and allows for code blocks to move between projects.


#A class is a logical code block that contains attributes and behavior.
#in python, a class is defined with the 'class' keyword.
#attributes can be variables and the behavior can be functions inside of it.

#A class provides a blue print for creating a object.

#An object is an instance of a class that you can create any number of them. 
#The state of an object is comprises it's attributes and behavior and each one has a unique identifier to distinguish it from other instances.

#The attributes and behavior of the class are what define the state of the object.
#There are methods which are the functions defined inside a class that determine the behavior of an object instance.

#Inheritance - creating a new class which is derivative of an existing one.
#The original is the parent class or super class and sub-class is the child class.

#Polymorphism - having many forms. The ability of a function to change it's behavior when called by different objects.
#in the context of python, a single function can act differently depending on the object that calls it.

#Encapsulation- Limit access to method and variables by encasing them in a single unit of scope such as a class.
#Encapsulation helps prevent unwanted modification, in affect reducing the occurrence errors in output.

#Abstraction - Hides implementation details for data security to make data more safer and secure. 

#Python does not support abstraction directly and uses inheritance to achieve it.


